-- Run SELECTs separately in DBeaver: UAT-MONITORING / EVTUAT4_COM / MONITORING.
-- Read-only discovery. No stored monitoring SQL is executed by this script.
SELECT USER, SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS current_schema FROM dual;

SELECT table_name, DBMS_METADATA.GET_DDL('TABLE', table_name, owner) AS ddl
FROM all_tables WHERE owner = 'MONITORING' ORDER BY table_name;

SELECT 'DSH_MENU' AS section,
  JSON_ARRAYAGG(JSON_OBJECT(* RETURNING CLOB) RETURNING CLOB) AS payload FROM MONITORING.DSH_MENU
UNION ALL SELECT 'DSH_DATASOURCE', JSON_ARRAYAGG(JSON_OBJECT(
  'DATASOURCE_ID' VALUE datasource_id, 'DISPLAY_NAME' VALUE display_name,
  'POOL_MAX' VALUE pool_max, 'CONNECT_TIMEOUT_MS' VALUE connect_timeout_ms,
  'IS_ACTIVE' VALUE is_active) RETURNING CLOB) FROM MONITORING.DSH_DATASOURCE
UNION ALL SELECT 'DSH_SUMMARY_QUERY', JSON_ARRAYAGG(JSON_OBJECT(* RETURNING CLOB) RETURNING CLOB)
  FROM MONITORING.DSH_SUMMARY_QUERY
UNION ALL SELECT 'DSH_SUMMARY_GROUP', JSON_ARRAYAGG(JSON_OBJECT(* RETURNING CLOB) RETURNING CLOB)
  FROM MONITORING.DSH_SUMMARY_GROUP
UNION ALL SELECT 'DSH_SUMMARY_FIELD', JSON_ARRAYAGG(JSON_OBJECT(* RETURNING CLOB) RETURNING CLOB)
  FROM MONITORING.DSH_SUMMARY_FIELD
UNION ALL SELECT 'DSH_DETAIL_TABLE', JSON_ARRAYAGG(JSON_OBJECT(* RETURNING CLOB) RETURNING CLOB)
  FROM MONITORING.DSH_DETAIL_TABLE
UNION ALL SELECT 'DSH_DETAIL_COLUMN', JSON_ARRAYAGG(JSON_OBJECT(* RETURNING CLOB) RETURNING CLOB)
  FROM MONITORING.DSH_DETAIL_COLUMN
UNION ALL SELECT 'TRIGGERS', JSON_ARRAYAGG(JSON_OBJECT(
  'name' VALUE trigger_name, 'table' VALUE table_name, 'status' VALUE status,
  'event' VALUE triggering_event) RETURNING CLOB) FROM all_triggers WHERE owner='MONITORING'
UNION ALL SELECT 'OBJECTS', JSON_ARRAYAGG(JSON_OBJECT(
  'name' VALUE object_name, 'type' VALUE object_type, 'status' VALUE status) RETURNING CLOB)
  FROM all_objects WHERE owner='MONITORING' AND object_type NOT IN ('INDEX','LOB','TABLE','SEQUENCE')
UNION ALL SELECT 'SESSION', JSON_ARRAYAGG(JSON_OBJECT(
  'user' VALUE USER, 'schema' VALUE SYS_CONTEXT('USERENV','CURRENT_SCHEMA')) RETURNING CLOB) FROM dual;

-- Optional focused recheck; these last queries were not run during initial discovery.
SELECT f.group_id, COUNT(*) AS orphan_count
FROM MONITORING.DSH_SUMMARY_FIELD f
WHERE NOT EXISTS (SELECT 1 FROM MONITORING.DSH_SUMMARY_GROUP g WHERE g.group_id = f.group_id)
GROUP BY f.group_id ORDER BY f.group_id;

SELECT menu_id, display_order, COUNT(*) AS duplicate_count
FROM MONITORING.DSH_SUMMARY_GROUP GROUP BY menu_id, display_order HAVING COUNT(*) > 1;
SELECT menu_id, display_order, COUNT(*) AS duplicate_count
FROM MONITORING.DSH_DETAIL_TABLE GROUP BY menu_id, display_order HAVING COUNT(*) > 1;
SELECT group_id, display_order, COUNT(*) AS duplicate_count
FROM MONITORING.DSH_SUMMARY_FIELD GROUP BY group_id, display_order HAVING COUNT(*) > 1;
